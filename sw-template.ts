export function generateServiceWorker(cacheFiles: string[], buildId: string): string {
  const files = [...new Set(cacheFiles.map((path) => path.replace(/^\/+/, '')).filter(Boolean))];
  return `/* generated by vite: app shell and emitted assets are cached under this registration scope */
const CACHE_PREFIX = 'home-offline-viewer-';
const CACHE = CACHE_PREFIX + ${JSON.stringify(buildId)};
const ASSETS = ${JSON.stringify(files)};
const scopeUrl = () => self.registration.scope;
const assetUrl = (path) => new URL(path, scopeUrl()).href;
const isOwnedUrl = (url) => {
  const scope = new URL(scopeUrl());
  return url.origin === scope.origin && url.href.startsWith(scope.href);
};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS.map(assetUrl))).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE).map((key) => caches.delete(key)))).then(() => self.clients.claim()));
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  const requestUrl = new URL(event.request.url);
  if (!isOwnedUrl(requestUrl)) return;
  if (event.request.mode === 'navigate' || event.request.destination === 'document') {
    event.respondWith(fetch(event.request).catch(() => caches.match(assetUrl('index.html')).then((cached) => cached || caches.match(scopeUrl()))));
    return;
  }
  event.respondWith(caches.match(event.request).then((cached) => cached || fetch(event.request).then((response) => {
    if (response.ok) caches.open(CACHE).then((cache) => cache.put(event.request, response.clone())).catch(() => undefined);
    return response;
  })));
});
`;
}
